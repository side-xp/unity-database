using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;

using UnityEngine;
using UnityEditor;

namespace SideXP.Database.EditorOnly
{

    /// <summary>
    /// Builds the definitions of the tables declared in code with <see cref="TableAttribute"/> and <see cref="ColumnAttribute"/>.
    /// </summary>
    internal static class CodeTables
    {

        #region Fields

        /// <summary>
        /// The flags used to collect the fields of each type of a table's hierarchy.
        /// </summary>
        /// <remarks>
        /// <see cref="BindingFlags.DeclaredOnly"/> is required: without it, the public and protected fields of base types are returned
        /// once per type of the hierarchy. Static fields are included only to warn about the ones marked as columns.
        /// </remarks>
        private const BindingFlags FieldFlags =
            BindingFlags.Instance | BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly;

        /// <summary>
        /// The character used in table names to group tables.
        /// </summary>
        private const char GroupSeparator = '/';

        /// <summary>
        /// The character that separates the names of the fields in the paths of the columns (see <see cref="ColumnAttribute.Path"/>),
        /// and in Unity's property paths.
        /// </summary>
        private const char PathSeparator = '.';

        /// <summary>
        /// The prefix of the names of the fields generated by the compiler for auto-properties.
        /// </summary>
        private const string BackingFieldPrefix = "<";

        /// <summary>
        /// The suffix of the names of the fields generated by the compiler for auto-properties.
        /// </summary>
        private const string BackingFieldSuffix = ">k__BackingField";

        /// <summary>
        /// A declaration with the default options, used for the types that have no declaration.
        /// </summary>
        private static readonly TableAttribute DefaultDeclaration = new TableAttribute();

        #endregion


        #region Public API

        /// <summary>
        /// Gets the types that may be tables: the types marked with <see cref="TableAttribute"/>, and the types derived from the ones
        /// marked with <see cref="TableAttribute.Inherited"/> enabled.
        /// </summary>
        /// <returns>Returns the candidate types, to pass to <see cref="Build(Type, ICollection{string})"/>.</returns>
        public static HashSet<Type> GetCandidateTypes()
        {
            HashSet<Type> candidates = new HashSet<Type>();
            foreach (Type declaringType in TypeCache.GetTypesWithAttribute<TableAttribute>())
            {
                candidates.Add(declaringType);

                TableAttribute declaration = declaringType.GetCustomAttribute<TableAttribute>(false);
                if (declaration != null && declaration.Inherited)
                    candidates.UnionWith(TypeCache.GetTypesDerivedFrom(declaringType));
            }
            return candidates;
        }

        /// <summary>
        /// Builds the definition of the table of a given type.
        /// </summary>
        /// <param name="type">The type of which to build the table.</param>
        /// <param name="warnings">The list to which the issues found in the declarations are added.</param>
        /// <param name="computedColumns">The computed columns of the project, added after the columns of the fields, or null to build
        /// the table without computed columns.</param>
        /// <returns>Returns the definition of the table, or null if the type is not a table.</returns>
        public static TableDefinition Build(Type type, ICollection<string> warnings, ComputedColumns computedColumns = null)
        {
            if (!TryResolveDeclaration(type, out Type declaringType, out TableAttribute declaration))
                return null;

            // Only warn on the type that carries the attribute, so a wrong declaration is reported once, not for each derived type
            bool isDeclaredHere = declaringType == type;

            if (!typeof(ScriptableObject).IsAssignableFrom(type))
            {
                if (isDeclaredHere)
                {
                    warnings.Add($"[{nameof(TableAttribute)}] is ignored on {type}: a table type must derive from " +
                        $"{nameof(ScriptableObject)}.");
                }

                return null;
            }

            if (type.ContainsGenericParameters)
            {
                // An open generic type can still pass its declaration on to its closed derived types
                if (isDeclaredHere && !declaration.Inherited)
                {
                    warnings.Add($"[{nameof(TableAttribute)}] is ignored on {type}: an open generic type can't have assets. Enable " +
                        $"{nameof(TableAttribute.Inherited)} to make its derived types tables instead.");
                }

                return null;
            }

            string name = isDeclaredHere
                ? GetDeclaredName(type, declaration)
                : GetInheritedName(type, declaringType, declaration);

            List<ColumnDefinition> columns = CollectColumns(type, warnings);
            if (computedColumns != null)
                columns.AddRange(computedColumns.GetColumns(type, warnings));

            return new TableDefinition(
                GetId(type),
                type,
                name,
                type.IsDefined(typeof(ObsoleteAttribute), false),
                declaration.HideAssetName,
                declaration.AllowRenameAsset,
                columns);
        }

        /// <summary>
        /// Finds the <see cref="TableAttribute"/> that applies to a given type: its own, or the nearest one of its base types if it
        /// has <see cref="TableAttribute.Inherited"/> enabled.
        /// </summary>
        /// <param name="type">The type of which to find the declaration.</param>
        /// <param name="declaringType">Outputs the type that carries the declaration.</param>
        /// <param name="declaration">Outputs the declaration that applies to the type.</param>
        /// <returns>Returns true if a declaration applies to the type.</returns>
        public static bool TryResolveDeclaration(Type type, out Type declaringType, out TableAttribute declaration)
        {
            for (Type current = type; current != null; current = current.BaseType)
            {
                TableAttribute attribute = current.GetCustomAttribute<TableAttribute>(false);
                if (attribute == null)
                    continue;

                // The nearest declaration wins: if it doesn't pass itself on, inheritance stops there
                if (current == type || attribute.Inherited)
                {
                    declaringType = current;
                    declaration = attribute;
                    return true;
                }

                break;
            }

            declaringType = null;
            declaration = null;
            return false;
        }

        /// <summary>
        /// Checks if the assets of a type can be renamed from the Database window, whatever the table that displays them.
        /// </summary>
        /// <remarks>
        /// The nearest <see cref="TableAttribute"/> of the type or its base types decides, even if it's not
        /// <see cref="TableAttribute.Inherited"/>: a type that is not a table itself, but is listed by the table of a base type, follows
        /// the declaration of that table.
        /// </remarks>
        /// <param name="assetType">The concrete type of the asset.</param>
        /// <returns>Returns the <see cref="TableAttribute.AllowRenameAsset"/> option of the nearest declaration, or the default of the
        /// option if no type of the hierarchy declares a table.</returns>
        /// <exception cref="ArgumentNullException">Thrown if the type is null.</exception>
        public static bool IsRenameAllowed(Type assetType)
        {
            if (assetType == null)
                throw new ArgumentNullException(nameof(assetType));

            for (Type current = assetType; current != null; current = current.BaseType)
            {
                TableAttribute attribute = current.GetCustomAttribute<TableAttribute>(false);
                if (attribute != null)
                    return attribute.AllowRenameAsset;
            }

            return DefaultDeclaration.AllowRenameAsset;
        }

        /// <summary>
        /// Collects the columns of a table type, from its root base type down to the type itself, then in declaration order within each
        /// type.
        /// </summary>
        /// <param name="tableType">The type of the table.</param>
        /// <param name="warnings">The list to which the issues found in the declarations of the columns are added.</param>
        /// <returns>Returns the valid columns of the table. Invalid columns are skipped.</returns>
        public static List<ColumnDefinition> CollectColumns(Type tableType, ICollection<string> warnings)
        {
            List<Type> hierarchy = new List<Type>();
            for (Type current = tableType; current != null && current != typeof(ScriptableObject); current = current.BaseType)
                hierarchy.Add(current);

            hierarchy.Reverse();

            List<ColumnDefinition> columns = new List<ColumnDefinition>();
            HashSet<string> ids = new HashSet<string>();
            foreach (Type declaringType in hierarchy)
            {
                FieldInfo[] fields = declaringType.GetFields(FieldFlags);
                // The order of GetFields() is not guaranteed, but metadata tokens follow the declaration order
                Array.Sort(fields, (a, b) => a.MetadataToken.CompareTo(b.MetadataToken));

                foreach (FieldInfo field in fields)
                {
                    ColumnAttribute[] attributes = (ColumnAttribute[])field.GetCustomAttributes(typeof(ColumnAttribute), false);
                    if (attributes.Length == 0)
                        continue;

                    string fieldLabel = $"{declaringType}.{field.Name}";
                    if (!IsSerializedField(field, out string reason))
                    {
                        warnings.Add($"The column of {fieldLabel} is skipped: {reason}.");
                        continue;
                    }

                    // The order of the attributes is the order of the columns of the field
                    foreach (ColumnAttribute attribute in attributes)
                    {
                        if (!TryResolvePath(field, attribute.Path, out List<FieldInfo> chain, out reason))
                        {
                            warnings.Add($"The column \"{attribute.Path}\" of {fieldLabel} is skipped: {reason}.");
                            continue;
                        }

                        // Unity already refuses to serialize two fields with the same name in a hierarchy, but a column must stay
                        // unique: the id is also the property path, so two columns with the same id would display the same value
                        string propertyPath = GetPropertyPath(chain);
                        if (!ids.Add(propertyPath))
                        {
                            warnings.Add($"A column of {fieldLabel} is skipped: another column already displays \"{propertyPath}\" (a " +
                                $"field with the same name in a base type, or a [{nameof(ColumnAttribute)}] with the same " +
                                $"{nameof(ColumnAttribute.Path)}).");
                            continue;
                        }

                        columns.Add(new ColumnDefinition(
                            propertyPath,
                            propertyPath,
                            chain,
                            GetColumnName(chain[chain.Count - 1], attribute),
                            GetColumnTooltip(chain),
                            attribute.Width));
                    }
                }
            }

            return columns;
        }

        /// <summary>
        /// Resolves the chain of fields of a column, from the field marked with <see cref="ColumnAttribute"/> to the value displayed by
        /// the column.
        /// </summary>
        /// <param name="field">The field marked with <see cref="ColumnAttribute"/>, already checked.</param>
        /// <param name="path">The <see cref="ColumnAttribute.Path"/> of the column. If null or blank, the column displays the marked
        /// field. The names are trimmed.</param>
        /// <param name="chain">Outputs the fields from the marked field to the displayed value, or null if the path is invalid.</param>
        /// <param name="reason">Outputs the reason why the path is invalid, or null if it's valid.</param>
        /// <returns>Returns true if the path is valid.</returns>
        public static bool TryResolvePath(FieldInfo field, string path, out List<FieldInfo> chain, out string reason)
        {
            chain = new List<FieldInfo> { field };
            reason = null;
            if (string.IsNullOrWhiteSpace(path))
                return true;

            foreach (string rawName in path.Split(PathSeparator))
            {
                string name = rawName.Trim();
                FieldInfo parent = chain[chain.Count - 1];
                Type parentType = parent.FieldType;

                if (name.Length == 0)
                    reason = $"the path \"{path}\" has an empty field name";
                else if (typeof(UnityEngine.Object).IsAssignableFrom(parentType))
                    reason = $"\"{parent.Name}\" is a reference to an object, which a path can't go through";
                else if (parent.IsDefined(typeof(SerializeReference), false))
                    reason = $"\"{parent.Name}\" is marked [{nameof(SerializeReference)}], so the type of its value can change";
                else if (parentType.IsArray || typeof(System.Collections.IList).IsAssignableFrom(parentType))
                    reason = $"\"{parent.Name}\" is an array or a list, which a path can't go through";

                if (reason != null)
                    break;

                FieldInfo nestedField = FindNestedField(parentType, name);
                if (nestedField == null)
                    reason = $"{parentType} has no field \"{name}\"";
                else if (!IsSerializedField(nestedField, out string nestedReason))
                    reason = $"\"{name}\" of {parentType} is not serialized ({nestedReason})";

                if (reason != null)
                    break;

                chain.Add(nestedField);
            }

            if (reason == null)
                return true;

            chain = null;
            return false;
        }

        /// <summary>
        /// Gets the stable identifier of the table of a given type.
        /// </summary>
        /// <param name="type">The type of the table.</param>
        /// <returns>Returns the GUID of the type's script file, or the type name with its assembly name if the type has no script file of
        /// its own.</returns>
        /// <inheritdoc cref="TableDefinition.Id" path="/remarks"/>
        public static string GetId(Type type)
        {
            // Unity associates a script file to a type only if the file is named after it, so only files with that name are candidates
            foreach (string guid in AssetDatabase.FindAssets($"t:{nameof(MonoScript)} {type.Name}"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (Path.GetFileNameWithoutExtension(path) != type.Name)
                    continue;

                MonoScript script = AssetDatabase.LoadAssetAtPath<MonoScript>(path);
                if (script != null && script.GetClass() == type)
                    return guid;
            }

            return GetTypeId(type);
        }

        /// <summary>
        /// Gets the identifier of a table type that has no script file of its own.
        /// </summary>
        /// <param name="type">The type of the table.</param>
        /// <returns>Returns the full name of the type and the name of its assembly, without the assembly version, so the identifier
        /// survives a version change of a DLL.</returns>
        public static string GetTypeId(Type type)
        {
            return $"{type.FullName}, {type.Assembly.GetName().Name}";
        }

        #endregion


        #region Private API

        /// <summary>
        /// Gets the name of a table from its own declaration.
        /// </summary>
        /// <param name="type">The type of the table.</param>
        /// <param name="declaration">The declaration of the table.</param>
        /// <returns>Returns the declared name, or the nicified type name if it's null or blank.</returns>
        private static string GetDeclaredName(Type type, TableAttribute declaration)
        {
            return !string.IsNullOrWhiteSpace(declaration.Name)
                ? declaration.Name.Trim()
                : ObjectNames.NicifyVariableName(type.Name);
        }

        /// <summary>
        /// Gets the name of a table inherited from the declaration of a base type: the nicified type name, in the same group as the
        /// base type's table.
        /// </summary>
        /// <param name="type">The type of the table.</param>
        /// <param name="declaringType">The base type that carries the declaration.</param>
        /// <param name="declaration">The declaration of the base type.</param>
        /// <returns>Returns the name of the inherited table.</returns>
        private static string GetInheritedName(Type type, Type declaringType, TableAttribute declaration)
        {
            string parentName = GetDeclaredName(declaringType, declaration);
            string ownName = ObjectNames.NicifyVariableName(type.Name);

            int separatorIndex = parentName.LastIndexOf(GroupSeparator);
            return separatorIndex >= 0
                ? $"{parentName.Substring(0, separatorIndex + 1)}{ownName}"
                : ownName;
        }

        /// <summary>
        /// Gets the header text of a column.
        /// </summary>
        /// <param name="field">The field that holds the value displayed in the column: the marked field, or the last field of its
        /// path.</param>
        /// <param name="attribute">The declaration of the column.</param>
        /// <returns>Returns the declared name, or the nicified field name if it's null or blank.</returns>
        private static string GetColumnName(FieldInfo field, ColumnAttribute attribute)
        {
            if (!string.IsNullOrWhiteSpace(attribute.Name))
                return attribute.Name.Trim();

            string fieldName = field.Name;
            // Use the name of the property for the backing field of an auto-property (declared with [field: Column])
            if (fieldName.StartsWith(BackingFieldPrefix) && fieldName.EndsWith(BackingFieldSuffix))
            {
                int length = fieldName.Length - BackingFieldPrefix.Length - BackingFieldSuffix.Length;
                fieldName = fieldName.Substring(BackingFieldPrefix.Length, length);
            }

            return ObjectNames.NicifyVariableName(fieldName);
        }

        /// <summary>
        /// Gets the text shown when hovering the header of a column.
        /// </summary>
        /// <param name="chain">The fields from the marked field to the displayed value.</param>
        /// <returns>Returns the <see cref="TooltipAttribute"/> of the nearest field to the value that has one, or null if none has
        /// one. The tooltip of a nested field describes the value better than the tooltip of the field that contains it.</returns>
        private static string GetColumnTooltip(IReadOnlyList<FieldInfo> chain)
        {
            for (int i = chain.Count - 1; i >= 0; i--)
            {
                TooltipAttribute tooltip = chain[i].GetCustomAttribute<TooltipAttribute>(false);
                if (tooltip != null)
                    return tooltip.tooltip;
            }
            return null;
        }

        /// <summary>
        /// Gets the property path of a column, which is also its identifier.
        /// </summary>
        /// <param name="chain">The fields from the marked field to the displayed value.</param>
        /// <returns>Returns the names of the fields, separated with dots, like Unity's property paths.</returns>
        private static string GetPropertyPath(IReadOnlyList<FieldInfo> chain)
        {
            string[] names = new string[chain.Count];
            for (int i = 0; i < chain.Count; i++)
                names[i] = chain[i].Name;

            return string.Join(PathSeparator.ToString(), names);
        }

        /// <summary>
        /// Finds a field of a type or of its base types, by its name or by the name of its auto-property.
        /// </summary>
        /// <param name="type">The type that contains the field.</param>
        /// <param name="name">The name of the field, or of the auto-property whose backing field to find.</param>
        /// <returns>Returns the found field, or null if there is none.</returns>
        private static FieldInfo FindNestedField(Type type, string name)
        {
            string backingFieldName = $"{BackingFieldPrefix}{name}{BackingFieldSuffix}";

            // GetField() doesn't return the private fields of base types: each type of the hierarchy is searched
            for (Type current = type; current != null && current != typeof(object); current = current.BaseType)
            {
                FieldInfo field = current.GetField(name, FieldFlags) ?? current.GetField(backingFieldName, FieldFlags);
                if (field != null)
                    return field;
            }
            return null;
        }

        /// <summary>
        /// Checks if a field is serialized by Unity, from its modifiers and attributes.
        /// </summary>
        /// <remarks>
        /// This doesn't check whether Unity can serialize the type of the field. That requires a serialized object, and is checked when
        /// the table loads its assets.
        /// </remarks>
        /// <param name="field">The field to check.</param>
        /// <param name="reason">Outputs the reason why the field is not serialized, or null if it is.</param>
        /// <returns>Returns true if the field is serialized.</returns>
        private static bool IsSerializedField(FieldInfo field, out string reason)
        {
            bool hasSerializeAttribute = field.IsDefined(typeof(SerializeField), false)
                || field.IsDefined(typeof(SerializeReference), false);

            if (field.IsStatic)
                reason = "static fields are not serialized";
            else if (field.IsInitOnly)
                reason = "readonly fields are not serialized";
            else if (field.IsNotSerialized)
                reason = $"the field is marked [{nameof(NonSerializedAttribute)}]";
            else if (!field.IsPublic && !hasSerializeAttribute)
                reason = $"non-public fields need [{nameof(SerializeField)}] to be serialized";
            else
                reason = null;

            return reason == null;
        }

        #endregion

    }

}
